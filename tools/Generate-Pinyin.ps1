# Writes src/Cantoria.Core/DiffSinger/pinyin.txt from Unicode's Unihan_Readings.txt: each Han
# character of the Basic Multilingual Plane with a kMandarin reading, under that reading without
# its tone (a voice's dictionary spells toneless pinyin, and ü as v). A character with two readings
# takes the first, kMandarin's customary one for simplified use.
#   tools/Generate-Pinyin.ps1 -Readings path\to\Unihan_Readings.txt
param([Parameter(Mandatory)][string]$Readings)

$out = Join-Path (Split-Path $PSScriptRoot -Parent) 'src\Cantoria.Core\DiffSinger\pinyin.txt'

function Toneless([string]$reading) {
    $d = $reading.Normalize([Text.NormalizationForm]::FormD).Replace("u$([char]0x308)", 'v')
    $s = [Text.StringBuilder]::new()
    foreach ($c in $d.ToCharArray()) {
        if ([Globalization.CharUnicodeInfo]::GetUnicodeCategory($c) -ne 'NonSpacingMark') { [void]$s.Append($c) }
    }
    $s.ToString().ToLowerInvariant()
}

$byReading = [Collections.Generic.SortedDictionary[string, Text.StringBuilder]]::new([StringComparer]::Ordinal)
$version = ''
$kept = 0; $dropped = 0
foreach ($line in [IO.File]::ReadLines($Readings)) {
    if ($line -match '^# Unicode Version (.+)$') { $version = $Matches[1] }
    if ($line -notmatch '^U\+([0-9A-F]{4})\tkMandarin\t(\S+)') { continue }
    $code = [Convert]::ToInt32($Matches[1], 16)
    $reading = Toneless $Matches[2]
    if ($reading -notmatch '^[a-z]+$') { $dropped++; continue }
    if (-not $byReading.ContainsKey($reading)) { $byReading[$reading] = [Text.StringBuilder]::new() }
    [void]$byReading[$reading].Append([char]$code)
    $kept++
}

$text = [Text.StringBuilder]::new()
[void]$text.Append("# Han characters by toneless Mandarin reading, from Unihan kMandarin, Unicode $version. See THIRD-PARTY-NOTICES.md. Generated by tools/Generate-Pinyin.ps1.`n")
foreach ($entry in $byReading.GetEnumerator()) { [void]$text.Append($entry.Key).Append(' ').Append($entry.Value.ToString()).Append("`n") }
[IO.File]::WriteAllBytes($out, [Text.UTF8Encoding]::new($false).GetBytes($text.ToString()))
"$kept characters, $($byReading.Count) readings, $dropped dropped -> $out"
