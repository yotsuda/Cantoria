# Writes src/Cantoria.Core/DiffSinger/pinyin-phrases.txt from phrase-pinyin-data's pinyin.txt
# (https://github.com/mozillazg/phrase-pinyin-data, MIT): the words in which a Han character is
# read otherwise than pinyin.txt (Unihan's customary reading) reads it alone - 长大 zhang, 银行
# hang - toneless, as a voice's dictionary spells. A word whose characters all read as they do
# alone is left out, unless one of its characters is read two ways somewhere in the data: such a
# word is kept so that it holds its characters together (行人 xing ren keeps 行 from being taken
# into 人行 ren hang's neighbour), since the words are found longest first.
#
# Two corrections of our own come first, written as words of the table (a character alone is a word
# of one): the characters Unihan's customary reading reads as almost no word of the data does (佛
# fu where 89 words read fo); and the words the data reads one way where a song means the other.
# A function word's reading alone (地 de, 还 hai, 了 le, 都 dou) is right though few words have it.
#   tools/Generate-PinyinPhrases.ps1 -Phrases path\to\phrase-pinyin-data\pinyin.txt
param([Parameter(Mandatory)][string]$Phrases)

$ownAlone = [ordered]@{
    '佛' = 'fo'; '长' = 'chang'; '琢' = 'zhuo'; '伺' = 'si'; '沓' = 'ta'; '泊' = 'bo'; '拓' = 'tuo'; '嚼' = 'jiao'; '卜' = 'bu'
}
$ownWords = [ordered]@{
    '落下' = 'luo xia'    # the data has only la xia (left behind); a song's 落下 falls
    '落了' = 'luo le'     # the data has only la le; 花落了
}

$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'src\Cantoria.Core\DiffSinger\pinyin-phrases.txt'

function Toneless([string]$reading) {
    $d = $reading.Normalize([Text.NormalizationForm]::FormD).Replace("u$([char]0x308)", 'v')
    $s = [Text.StringBuilder]::new()
    foreach ($c in $d.ToCharArray()) {
        if ([Globalization.CharUnicodeInfo]::GetUnicodeCategory($c) -ne 'NonSpacingMark') { [void]$s.Append($c) }
    }
    $s.ToString().ToLowerInvariant()
}

# Each character's reading alone, as ChinesePhonemizer has it.
$alone = [Collections.Generic.Dictionary[char, string]]::new()
foreach ($line in [IO.File]::ReadLines((Join-Path $root 'src\Cantoria.Core\DiffSinger\pinyin.txt'))) {
    $space = $line.IndexOf(' ')
    if ($line.StartsWith('#') -or $space -le 0) { continue }
    $reading = $line.Substring(0, $space)
    foreach ($c in $line.Substring($space + 1).ToCharArray()) { $alone[$c] = $reading }
}
$unihan = [Collections.Generic.Dictionary[char, string]]::new($alone)
foreach ($c in $ownAlone.Keys) { $alone[[char]$c] = $ownAlone[$c] }

# The words, the first reading of each, toneless; and every reading each character is given.
$words = [Collections.Generic.Dictionary[string, string[]]]::new([StringComparer]::Ordinal)
$order = [Collections.Generic.List[string]]::new()
$readings = [Collections.Generic.Dictionary[char, Collections.Generic.HashSet[string]]]::new()
$version = ''
$skipped = 0
foreach ($line in [IO.File]::ReadLines($Phrases)) {
    if ($line -match '^# version: (.+)$') { $version = $Matches[1] }
    if ($line -notmatch '^([^#:\s]+):\s*([^#]+)') { continue }
    $word = $Matches[1]
    $sung = @(($Matches[2].Trim() -split '\s+') | ForEach-Object { Toneless $_ })
    if ($sung.Count -ne $word.Length -or ($sung | Where-Object { $_ -notmatch '^[a-z]+$' }) -or
        ($word.ToCharArray() | Where-Object { -not $alone.ContainsKey($_) })) { $skipped++; continue }
    for ($i = 0; $i -lt $word.Length; $i++) {
        if (-not $readings.ContainsKey($word[$i])) { $readings[$word[$i]] = [Collections.Generic.HashSet[string]]::new() }
        [void]$readings[$word[$i]].Add($sung[$i])
    }
    if (-not $words.ContainsKey($word)) { $words[$word] = $sung; $order.Add($word) }
}
foreach ($word in $ownWords.Keys) {
    if (-not $words.ContainsKey($word)) { $order.Add($word) }
    $words[$word] = $ownWords[$word] -split ' '
}

$text = [Text.StringBuilder]::new()
[void]$text.Append("# Words whose characters are read otherwise than alone, or hold a character read two ways, toneless; from phrase-pinyin-data $version pinyin.txt. See THIRD-PARTY-NOTICES.md. Generated by tools/Generate-PinyinPhrases.ps1.`n")
foreach ($c in $ownAlone.Keys) {
    if ($unihan[[char]$c] -ne $ownAlone[$c]) { [void]$text.Append($c).Append(' ').Append($ownAlone[$c]).Append("`n") }
}
$differ = 0; $hold = 0
foreach ($word in $order) {
    $sung = $words[$word]
    $other = $false; $twoWays = $false
    for ($i = 0; $i -lt $word.Length; $i++) {
        if ($sung[$i] -ne $alone[$word[$i]]) { $other = $true }
        if ($readings[$word[$i]].Count -gt 1) { $twoWays = $true }
    }
    if ($other) { $differ++ } elseif ($twoWays) { $hold++ } else { continue }
    [void]$text.Append($word).Append(' ').Append($sung -join ' ').Append("`n")
}
[IO.File]::WriteAllBytes($out, [Text.UTF8Encoding]::new($false).GetBytes($text.ToString()))
"$($order.Count) words read, $skipped skipped; $differ read otherwise than alone, $hold kept to hold their characters -> $out ($([math]::Round((Get-Item $out).Length / 1KB)) KB)"
